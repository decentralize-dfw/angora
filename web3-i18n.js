export function translateTurkish(value,context='general'){
 const key=normalized(value);let result=context==='room'?ROOM_NAMES[key]:undefined;
 result??=TR[key]??lower.get(key.toLowerCase());
 if(result===undefined){
  let match;const parts=key.split(' · ');
  if(FLOOR_NAMES[parts[0]]&&parts.length>1){
   result=[FLOOR_NAMES[parts[0]],...parts.slice(1).map(part=>/^Photograph \d+$/.test(part)?part.replace('Photograph','Fotoğraf'):/^\d+ viewpoints$/.test(part)?part.replace('viewpoints','fotoğraf noktası'):roomName(part))].join(' · ');
  }else if((match=key.match(/^(Garden|Entrance|First|Attic) \/ (\d+) of 4$/)))result=`${floorName(match[1])} · ${match[2]}/4`;
  else if((match=key.match(/^(Garden|Entrance|First|Attic) level isometric overview$/)))result=`${floorName(match[1])} — izometrik görünüm`;
  else if((match=key.match(/^(Garden|Entrance|First|Attic) floor plan, selected photograph and viewing direction$/)))result=`${floorName(match[1])} planı; seçili fotoğraf noktası ve kameranın baktığı yön`;
  else if((match=key.match(/^(.+), (Garden|Entrance|First|Attic) level$/)))result=`${floorName(match[2])} · ${roomName(match[1])}`;
  else if((match=key.match(/^Photograph (\d+), (.+)$/)))result=`Fotoğraf ${match[1]}: ${roomName(match[2])}`;
  else if((match=key.match(/^Enlarge (.+) photograph (\d+)$/)))result=`Fotoğrafı aç: ${roomName(match[1])} · ${match[2]}`;
  else if((match=key.match(/^Enlarge (.+)$/)))result=`Fotoğrafı aç: ${translateTurkish(match[1])}`;
  else if((match=key.match(/^(\d+) · (.+)$/)))result=`${match[1]} · ${roomName(match[2])}`;
  else if((match=key.match(/^Open (garden|entrance|first|attic) floor plan ↗$/i)))result=`${floorName(match[1])} planını aç ↗`;
  else if((match=key.match(/^(Garden|Entrance|First|Attic) · (\d+) viewpoints$/)))result=`${floorName(match[1])} · ${match[2]} fotoğraf noktası`;
  else if((match=key.match(/^(Garden|Entrance|First|Attic) plan$/)))result=`${floorName(match[1])} planı`;
  else if((match=key.match(/^([\d.]+) m² · supplied room schedule$/)))result=`${match[1].replace('.',',')} m² · projeye göre`;
  else if((match=key.match(/^Nearby viewpoints: (.+)\. Choose a number below\.$/)))result=`Yakın fotoğraf noktaları: ${match[1]}. Aşağıdaki numaralardan birini seçin.`;
  else if(/^\d+\.\d+ m$/.test(key))result=key.replace('.',',');
  else if(/^₺[\d,]+$/.test(key))result=key.replaceAll(',','.');
  else result=key;
 }
 return spaced(value,result);
}
